package com.iemms.dto;

public class EquipmentDashboardDto {
	private Long totalEquipment;
	private Long inactiveEquipment;
	private Long activeEquipment;
	private Long maintenanceEquipment;
	
	public EquipmentDashboardDto() {
		
	}

	public Long getTotalEquipment() {
		return totalEquipment;
	}

	public void setTotalEquipment(Long totalEquipment) {
		this.totalEquipment = totalEquipment;
	}

	public Long getInactiveEquipment() {
		return inactiveEquipment;
	}

	public void setInactiveEquipment(Long inactiveEquipment) {
		this.inactiveEquipment = inactiveEquipment;
	}

	public Long getActiveEquipment() {
		return activeEquipment;
	}

	public void setActiveEquipment(Long activeEquipment) {
		this.activeEquipment = activeEquipment;
	}

	public Long getMaintenanceEquipment() {
		return maintenanceEquipment;
	}

	public void setMaintenanceEquipment(Long maintenanceEquipment) {
		this.maintenanceEquipment = maintenanceEquipment;
	}
	
	
}
